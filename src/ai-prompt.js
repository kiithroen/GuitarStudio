(function(root){
  'use strict';

  function buildAiPromptText(beats, bpm){
    var bpb = Number(beats) || 4;
    if ([2, 3, 4, 6, 8, 9].indexOf(bpb) < 0) bpb = 4;
    var selectedBpm = Number(bpm) || 64;
    var firstSlots = ['E4@1/F4@1'];
    while (firstSlots.length < bpb) firstSlots.push('r');
    var secondSlots = ['C4@2'];
    while (secondSlots.length < bpb) secondSlots.push('-');
    var firstMeasure = '[C] ' + firstSlots.join(' ') + ' | ""';
    var secondMeasure = '[C] ' + secondSlots.join(' ') + ' | ""';
    var sampleScore = firstMeasure + '\n' + secondMeasure;
    var gridDescription = bpb === 6
      ? '현재 선택은 6칸이며 6/8의 8분음표 칸으로 해석해.'
      : bpb === 8
        ? '현재 선택은 8칸이며 4/4의 8분음표 칸으로 해석해.'
        : bpb === 9
          ? '현재 선택은 9칸이며 9/8의 8분음표 칸으로 해석해.'
          : bpb === 3
            ? '현재 선택은 3칸이며 3/4의 4분음표 칸으로 해석해. 3/4 셋잇단음표는 3칸으로 환산하지 말고 해당 한 칸 안을 음/음/음처럼 3분할해.'
          : '현재 선택은 ' + bpb + '칸이며 각 칸은 4분음표야.';
    var bpmUnit = ([6, 8, 9].indexOf(bpb) >= 0) ? '8분음표 한 칸' : '4분음표 한 칸';
    return [
      '첨부한 기타 악보 사진을 읽고 아래 규칙에 따라 앱에 붙여넣을 악보를 만들어줘. 보이지 않거나 확정할 수 없는 내용은 추측하지 말고 불확실성으로 보고해줘.',
      '',
      '[마디와 표기 규칙]',
      '- 마디는 줄바꿈 또는 `//`로만 나눠. `/`는 박 안의 서브토큰 구분자이며 앞뒤 공백 없이 써.',
      '- 모든 마디의 첫 항목은 코드 헤더 `[코드]`야. 사진에 코드가 없거나 읽을 수 없으면 `[-]`로 적어 원본에 코드가 없음을 표시해. 코드를 추론해 원본 코드처럼 채우지 마. 별도의 앱 자동 추론은 사용자가 선택할 수 있어.',
      '- 악보의 각 칸은 공백으로 구분하고, 한 칸 안의 균등 분할은 `음/음`으로 써. 2·3·4분할만 지원해.',
      '- 쉼은 `r`, 바로 앞 음이나 화음 전체를 다시 치지 않고 이어가는 것은 `-`로 써. `-`는 악보 시작이나 쉼 뒤에 올 수 없어. `.`은 쓰지 마.',
      '- 모든 마디의 칸을 빠짐없이 적어. 입력이 부족하거나 모호하면 임의로 채우지 말고 변환을 멈춰 위치를 알려줘.',
      '- 가사나 설명은 `|` 뒤에 JSON 문자열로 적어. 예: `| "가사 또는 설명"`',
      '- 불명확한 음은 위치를 지우지 말고 `?`로 남긴 뒤, 코드블록 밖의 불확실성 목록에 마디와 박 위치를 적어. `?`는 앱에서 저장이 막히므로 임의의 음·쉼·박자·템포·운지를 채우지 마.',
      '- 출력 코드블록 안에는 악보만 넣고 설명이나 불확실성 안내를 섞지 마.',
      '',
      '[TAB 악보]',
      '- 6개 줄은 위에서부터 1~6번 줄이야. TAB 숫자는 왼손 손가락 번호가 아니라 실제 프렛 번호야. 모든 음에 실제 줄 번호를 `음@줄번호`로 붙여. 같은 음높이가 여러 줄에서 가능하면 실제 줄을 확인해 각각 표시해.',
      '- 앱 기본 열린현 MIDI는 1번줄 E4, 2번줄 B3, 3번줄 G3, 4번줄 D3, 5번줄 A2, 6번줄 E2야. 실제 프렛 수를 해당 열린현에 더해 음높이를 판독해. `[1~6]`은 줄 번호이며 특정 포지션을 단정하지 않아.',
      '- 왼손 운지가 실제로 보이면 운지 번호를 음 앞에 붙일 수 있어. 안 보이면 숫자 prefix를 생략해. TAB의 10·11·12는 각각 한 개의 프렛 번호야.',
      '- 한 줄의 같은 위치에 서로 다른 프렛 숫자가 겹쳐 보이면 임의로 고르지 말고 불확실성으로 보고해.',
      '- 이미지에 표준 튜닝이 아닌 실제 튜닝이 명시되어 있으면 앱 미지원이라고 알리고 악보 출력을 중단해. 12프렛보다 높은 프렛도 앱 미지원이라고 알리고 추측하지 마.',
      '',
      '[오선보와 기타 표기]',
      '- 조표, 임시표, 제자리표, 마디 안 임시표 초기화, 낮은음자리표, 동시 성부, 붙임줄, 점음표, 쉼표, 반복 기호를 확인해.',
      '- 클래식 기타의 높은음자리표 기보 옥타브와 실제 울림 옥타브 차이를 확인하고 TAB과 대조해. 일반 기타의 8vb 표기가 확인되면 앱 실음 기준으로 한 옥타브 낮춰. 악보 표기만으로 옥타브를 단정하지 마.',
      '- ' + gridDescription,
      '- 원본 박자표의 분자와 분모, 박 단위를 확인해. 앱 선택은 마디당 ' + bpb + '칸이야. 원본의 박 단위가 이 선택으로 표현되지 않을 때만 변환을 멈추고 실제 박자표와 권장 선택값을 명확히 알려. 예시를 억지로 변형하지 마.',
      '- 독립 길이 성부, 부분 붙임줄, 슬러/꾸밈음, 못갖춘마디, 가변 박자, 반복 기호는 앱이 해석하지 못해. 이를 단순한 음이나 쉼으로 바꾸지 말고 이미지 모드 사용을 권해.',
      '- 인쇄 템포의 음표 단위가 ' + bpmUnit + '과 다르면 원본 템포 단위와 앱의 BPM/칸 환산값을 각각 밝혀. 한 번 클릭이 한 칸이고 BPM은 1분 동안 진행하는 칸 수야.',
      '- 카포 상대 폼은 유지해. 카포가 실제로 읽힌 경우에만 제목에 확인된 `Capo n` 위치를 적어.',
      '- 인쇄된 템포가 읽히면 그 값을 써. 인쇄 템포가 없으면 앱에서 선택한 BPM ' + selectedBpm + '을 사용하고, 코드블록 밖에서 이 값이 이미지 판독값이 아니라 사용자 선택값임을 밝혀. 템포를 추측하지 마.',
      '',
      '[문법 예시: 실제 사진 변환 결과가 아님]',
      '첫 음의 박내 분할과 두 번째 마디의 실제 음을 보이는 형식 예시야. 실제 판독 결과로 복사하지 마.',
      firstMeasure,
      secondMeasure,
      '',
      '[실제 결과 출력 형식 1: 코드블록 안에는 악보 마디만, 한 줄에 한 마디]',
      '제목과 박자 정보는 코드블록 밖에 적어.',
      '[코드] 음@줄번호 r ... | "가사 또는 설명"',
      '',
      '[실제 결과 출력 형식 2: TSV 한 행, 다섯 열]',
      '열은 제목, 마디당 박 수, BPM, 설명, 악보야. 마지막 열의 마디 사이는 ` // `로 구분해. 1번 형식과 같은 음과 박자로 출력해. 인쇄된 카포가 확인된 경우에만 제목에 Capo 표기를 넣어.',
      '제목\t' + bpb + '\t' + selectedBpm + '\t변환 악보\t' + sampleScore.replace(/\n/g, ' // ')
    ].join('\n');
  }

  if (typeof module !== 'undefined' && module.exports) module.exports = buildAiPromptText;
  else root.buildAiPromptText = buildAiPromptText;
})(typeof globalThis !== 'undefined' ? globalThis : this);
